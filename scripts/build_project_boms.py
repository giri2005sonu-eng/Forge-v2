def parse(recipe):
    out = []
    for tok in recipe.split():
        key, _, q = tok.partition("*")
        assert key in L, f"unknown archetype {key!r} in recipe"
        out.append((key, int(q) if q else 1))
    return out

def build():
    projects = {}
    for src, fname, recipes in (("general", "projects.csv", G), ("competition", "competition_projects.csv", C)):
        rows = list(csv.DictReader(open(ROOT / fname, encoding="utf-8-sig")))
        ids = [r["id"] for r in rows]
        missing, extra = set(ids) - set(recipes), set(recipes) - set(ids)
        assert not missing and not extra, f"{src}: missing={missing} extra={extra}"
        for r in rows:
            parts, seen = [], set()
            for key, qty in parse(recipes[r["id"]]):
                assert key not in seen, f"{r['id']}: duplicate {key}"
                seen.add(key); role, name, query, *note = L[key]
                parts.append(dict(part=key, id="d_" + key, role=role, name=name, query=query, qty=qty, note=note[0] if note else ""))
            projects[f"{src}:{r['id']}"] = dict(
                key=f"{src}:{r['id']}", project_source=src, id=r["id"], label=r["name"], domain=r["domain"], description=r["description"],
                catalog_cost_inr=int(r["cost_inr"] or 0), safety=[s for s in r["safety"].split("|") if s],
                competition_event=r.get("competition_event", ""), constraints=r.get("constraints", ""),
                software_only=not parts, bom_status="draft", reviewed=False, authored_by="FORGE team draft from CSV fields; not AI at runtime",
                notes=NOTES.get(r["id"], []), parts=parts)
    lib = {k: dict(role=v[0], name=v[1], query=v[2], note=v[3] if len(v) > 3 else "") for k, v in L.items()}
    return dict(schema_version=1, note="Component lists only. No prices, no verified specs. bom_status 'draft' = names and quantities proposed, nothing verified.", projects=projects, library=lib)

